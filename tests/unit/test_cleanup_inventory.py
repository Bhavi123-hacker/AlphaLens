"""TEST_ONLY filesystem fixtures for protection of private and linked content."""

import os
import subprocess
from pathlib import Path

import pytest
from scripts import cleanup_inventory as cleanup


def test_protected_and_escaping_targets_never_delete(tmp_path: Path) -> None:
    protected = tmp_path / ".local-data" / "__pycache__"
    protected.mkdir(parents=True)
    evidence = protected / "model.pyc"
    evidence.write_bytes(b"TEST_ONLY protected content")
    for relative in (
        ".local-data/__pycache__",
        ".LOCAL-DATA/__pycache__",
        "../__pycache__",
        ".git",
        ".venv",
    ):
        with pytest.raises(ValueError):
            cleanup.validate_cache(tmp_path, relative, set())
    assert evidence.read_bytes() == b"TEST_ONLY protected content"


def test_tracked_or_unexpected_cache_content_is_retained(tmp_path: Path) -> None:
    cache = tmp_path / "__pycache__"
    cache.mkdir()
    evidence = cache / "retained.pyc"
    evidence.write_bytes(b"TEST_ONLY tracked content")
    with pytest.raises(ValueError, match="tracked"):
        cleanup.validate_cache(tmp_path, "__pycache__", {"__pycache__/retained.pyc"})
    unknown = cache / "important.json"
    unknown.write_text("TEST_ONLY important evidence", encoding="utf-8")
    with pytest.raises(ValueError, match="Unexpected"):
        cleanup.remove_cache(tmp_path, cache)
    assert evidence.exists() and unknown.exists()


def test_reviewed_disposable_cache_removed_with_exact_byte_accounting(tmp_path: Path) -> None:
    cache = tmp_path / "__pycache__"
    cache.mkdir()
    (cache / "example.cpython-312.pyc").write_bytes(b"TEST_ONLY generated bytecode")
    source = tmp_path / "example.py"
    source.write_text("# TEST_ONLY source survives\n", encoding="utf-8")
    target = cleanup.validate_cache(tmp_path, "__pycache__", set())
    result = cleanup.remove_cache(tmp_path, target)
    assert result["files"] == 1
    assert result["logical_bytes"] == len(b"TEST_ONLY generated bytecode")
    assert not cache.exists() and source.exists()


def test_linked_cache_is_refused_without_following_target(tmp_path: Path) -> None:
    target = tmp_path / "outside"
    target.mkdir()
    preserved = target / "retained.pyc"
    preserved.write_bytes(b"TEST_ONLY linked evidence")
    link = tmp_path / "__pycache__"
    if os.name == "nt":
        subprocess.run(
            ["cmd", "/c", "mklink", "/J", str(link), str(target)],
            check=True,
            capture_output=True,
        )
    else:
        link.symlink_to(target, target_is_directory=True)
    with pytest.raises(ValueError, match="Reparse"):
        cleanup.validate_cache(tmp_path, "__pycache__", set())
    assert preserved.exists()
