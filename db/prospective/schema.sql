PRAGMA user_version = 1;
CREATE TABLE IF NOT EXISTS forecasts (
    id TEXT PRIMARY KEY, identity TEXT NOT NULL UNIQUE,
    payload TEXT NOT NULL, sha256 TEXT NOT NULL, recorded_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS outcomes (
    id TEXT PRIMARY KEY, forecast_id TEXT NOT NULL REFERENCES forecasts(id),
    payload TEXT NOT NULL, sha256 TEXT NOT NULL, recorded_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS outcomes_forecast ON outcomes(forecast_id, recorded_at DESC);
CREATE TABLE IF NOT EXISTS notification_cursor (
    singleton INTEGER PRIMARY KEY CHECK(singleton=1), position INTEGER NOT NULL CHECK(position>=0)
);
INSERT OR IGNORE INTO notification_cursor VALUES(1,0);
CREATE TRIGGER IF NOT EXISTS forecast_no_update BEFORE UPDATE ON forecasts
BEGIN SELECT RAISE(ABORT, 'IMMUTABLE_FORECAST'); END;
CREATE TRIGGER IF NOT EXISTS forecast_no_delete BEFORE DELETE ON forecasts
BEGIN SELECT RAISE(ABORT, 'IMMUTABLE_FORECAST'); END;
CREATE TRIGGER IF NOT EXISTS outcome_no_update BEFORE UPDATE ON outcomes
BEGIN SELECT RAISE(ABORT, 'IMMUTABLE_OUTCOME'); END;
CREATE TRIGGER IF NOT EXISTS outcome_no_delete BEFORE DELETE ON outcomes
BEGIN SELECT RAISE(ABORT, 'IMMUTABLE_OUTCOME'); END;
