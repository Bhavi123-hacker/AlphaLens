"""Predeclared V2 acceptance readiness; no original accepted-ranking writes.

Review documents are external evidence pinned by an operator-controlled trust
registry. This module never authors an independent approval or configures trust.
"""

from __future__ import annotations

import hashlib
import json
import math
from collections.abc import Mapping
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from alphalens_api.auth.permissions import verify

CRITERIA_VERSION = "nse.v2.prospective-acceptance.1"
CRITERIA = {
    "future_decision_dates": 126,
    "eligible_outcomes": 1000,
    "securities": 30,
    "quarters": 2,
    "date_block_bootstrap_lower_balanced_accuracy_improvement": 0.02,
    "mean_date_rank_ic": 0.02,
    "bootstrap_block_dates": 20,
    "bootstrap_draws": 1000,
    "bootstrap_seed": 42,
}


def _hash(body: Any) -> str:
    return hashlib.sha256(
        json.dumps(body, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()
    ).hexdigest()


def _number(value: Any) -> float | None:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None
    return float(value) if math.isfinite(value) else None


def evidence_bundle(
    model_id: str,
    dataset_id: str,
    protocol_id: str,
    prospective: Mapping[str, Any],
    economics: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """A content-addressed review input, never an approval generated by Codex."""
    body = {
        "criteria_version": CRITERIA_VERSION,
        "criteria": CRITERIA,
        "model_id": model_id,
        "dataset_id": dataset_id,
        "protocol_id": protocol_id,
        "prospective": dict(prospective),
        "economics": dict(economics or {}),
        "engineering_review": "SEPARATE_FROM_INDEPENDENT_RESEARCH_APPROVAL",
    }
    return {**body, "bundle_id": _hash(body)}


def review_template(bundle: Mapping[str, Any]) -> dict[str, Any]:
    return {
        "bundle_id": bundle["bundle_id"],
        "reviewer_id": None,
        "reviewed_at": None,
        "independence_statement": None,
        "review_document_sha256": None,
        "decision": "PENDING_EXTERNAL_REVIEW",
        "instructions": (
            "External reviewer prepares a separate review; operator pins its identity "
            "and document hash in the private trust registry."
        ),
    }


def import_review(root: Path, bundle: Mapping[str, Any], review: Mapping[str, Any]) -> str:
    """Verify externally pinned review evidence; do not trust a passed flag.

    Registry creation is deliberately outside this workflow. Its entries identify
    an externally obtained reviewer/document and exact evidence bundle. A reviewer
    document is not supplied as executable code. Local test data can verify this
    machinery but cannot satisfy genuine independent research requirements.
    """
    body = {key: value for key, value in bundle.items() if key != "bundle_id"}
    if _hash(body) != bundle.get("bundle_id"):
        raise ValueError("REVIEW_BUNDLE_HASH_MISMATCH")
    registry = root / "independent-review-trust.json"
    if not registry.is_file() or registry.is_symlink():
        raise ValueError("EXTERNAL_REVIEWER_NOT_CONFIGURED")
    verify(root)
    verify(registry, directory=False)
    trusted = json.loads(registry.read_text(encoding="utf-8"))
    identifier = review.get("reviewer_id")
    if not isinstance(identifier, str) or identifier.upper().startswith(("CODEX", "AGENT", "TEST")):
        raise ValueError("INDEPENDENT_EXTERNAL_HUMAN_REVIEW_REQUIRED")
    entries = trusted.get("reviewers", {})
    reviewer = entries.get(identifier, {})
    if (
        not reviewer.get("operator_verified_external_identity")
        or not reviewer.get("independence_evidence_sha256")
        or review.get("bundle_id") != bundle["bundle_id"]
        or reviewer.get("approved_bundle_id") != bundle["bundle_id"]
        or not review.get("independence_statement")
        or review.get("decision") != "APPROVE_RESEARCH_EVIDENCE"
        or review.get("review_document_sha256") != reviewer.get("review_document_sha256")
    ):
        raise ValueError("PINNED_INDEPENDENT_REVIEW_EVIDENCE_REQUIRED")
    document_name = reviewer.get("review_document")
    if not isinstance(document_name, str) or Path(document_name).name != document_name:
        raise ValueError("LOCAL_PINNED_REVIEW_DOCUMENT_REQUIRED")
    document = root / document_name
    if not document.is_file() or document.is_symlink():
        raise ValueError("LOCAL_PINNED_REVIEW_DOCUMENT_REQUIRED")
    verify(document, directory=False)
    if hashlib.sha256(document.read_bytes()).hexdigest() != review["review_document_sha256"]:
        raise ValueError("INDEPENDENT_REVIEW_DOCUMENT_HASH_MISMATCH")
    reviewed = datetime.fromisoformat(str(review.get("reviewed_at")))
    if reviewed.tzinfo is None or reviewed > datetime.now(UTC):
        raise ValueError("ACTUAL_EXTERNAL_REVIEW_TIMESTAMP_REQUIRED")
    return _hash(dict(review))


def readiness(
    bundle: Mapping[str, Any], *, verified_review_id: str | None = None
) -> dict[str, Any]:
    """Report independent gates; accepted publication adapter remains unavailable."""
    prospective = bundle.get("prospective", {})
    metrics = prospective.get("metrics", {})
    sample_checks = {
        "126_future_decision_dates": prospective.get("future_decision_dates", 0) >= 126,
        "1000_eligible_matured_outcomes": prospective.get("outcomes", 0) >= 1000,
        "30_securities": prospective.get("securities_with_outcomes", 0) >= 30,
        "two_quarters": prospective.get("outcome_quarters", 0) >= 2,
    }
    intervals = metrics.get("date_block_bootstrap_improvement_intervals", {})
    improvement = all(
        isinstance(intervals.get(name), list)
        and len(intervals[name]) == 2
        and (_number(intervals[name][0]) or -1) > 0.02
        for name in (
            "baseline_majority_score",
            "baseline_momentum_score",
            "baseline_mean_reversion_score",
        )
    )
    brier = _number(metrics.get("brier"))
    baselines = metrics.get("baselines", {})
    calibrated_claim = metrics.get("claims_calibrated_probabilities") is True
    majority_brier = _number(baselines.get("baseline_majority_score", {}).get("brier"))
    brier_better = not calibrated_claim or (
        brier is not None and majority_brier is not None and brier < majority_brier
    )
    research_checks = {
        "block_95_lower_improvement_above_two_points": improvement,
        "brier_better_than_majority_if_calibrated_claimed": brier_better,
        "mean_date_rank_ic_above_002": (_number(metrics.get("mean_date_rank_ic")) or -1) > 0.02,
        "positive_cross_regime_stability": metrics.get("positive_cross_regime_stability") is True,
        "independently_reviewed_calibration": metrics.get("calibration_independently_reviewed")
        is True,
    }
    economics = bundle.get("economics", {})
    economic_fields = (
        "compatible_executable_entry_exit",
        "complete_corporate_actions_and_dividends",
        "appropriate_independent_benchmark",
        "documented_transaction_costs_and_capacity",
        "positive_net_baseline_relative_return_with_uncertainty",
        "drawdown_robustness",
    )
    economic_checks = {field: economics.get(field) is True for field in economic_fields}
    return {
        "criteria_version": CRITERIA_VERSION,
        "sample_requirements": sample_checks,
        "research_requirements": research_checks,
        "economic_requirements": economic_checks,
        "prospective_evidence": "PASS" if all(sample_checks.values()) else "PENDING",
        "predictive_edge": "PASS"
        if all(research_checks.values()) and all(sample_checks.values())
        else "NO_DEMONSTRATED_EDGE",
        "economic_edge": "PASS" if all(economic_checks.values()) else "PENDING",
        "independent_review": "EVIDENCE_IMPORTED"
        if verified_review_id
        else "PENDING_EXTERNAL_REVIEW",
        "independent_review_id": verified_review_id,
        "accepted_publication_adapter": "NOT_CONFIGURED_OR_AUTHORIZED",
        "independent_acceptance": False,
        "accepted_top_5_10_20": False,
        "state": "PROSPECTIVE_EVALUATION_IN_PROGRESS"
        if prospective.get("eligible_forecasts", 0)
        else "BACKTESTED_NOT_PROSPECTIVELY_ACCEPTED",
        "limitations": [
            "A passed historical development comparison is not independent evidence.",
            "Importing a review does not publish to original P12 rankings.",
            "No independent reviewer or acceptance is manufactured by this workflow.",
        ],
    }
